// Package codexgen keeps the bundled Codex CLI home in sync with the vault:
// the downstream key ticked 「给 Codex 用」 in the panel, the gateway port and
// the model name are written into <dataDir>/codex/{auth.json,config.toml} on
// every unlock and panel change, so Codex opens ready-to-use against the
// relay.  Everything (chat history included) stays on the USB stick via
// CODEX_HOME.
package codexgen

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"usbridge/internal/vault"
)

// Home is the CODEX_HOME directory inside the USB data dir.
func Home(dataDir string) string { return filepath.Join(dataDir, "codex") }

// DefaultModel is written into config.toml when the panel has no override.
const DefaultModel = "gpt-5.1-codex"

// Sync rewrites auth.json + config.toml.  With no selected+enabled key,
// auth.json is REMOVED so a stale key never leaks into Codex (config.toml is
// still written; Codex then fails fast with "not logged in").
func Sync(dataDir string, port int, keys []*vault.DownstreamKey, model string) error {
	home := Home(dataDir)
	if err := os.MkdirAll(home, 0o755); err != nil {
		return err
	}
	var sel *vault.DownstreamKey
	for _, k := range keys {
		if k.CodexUse && k.Enabled {
			sel = k
			break
		}
	}
	auth := filepath.Join(home, "auth.json")
	if sel == nil {
		os.Remove(auth)
	} else {
		b, _ := json.MarshalIndent(map[string]string{"OPENAI_API_KEY": sel.Key}, "", "  ")
		if err := atomicWrite(auth, b); err != nil {
			return err
		}
	}
	if port <= 0 {
		port = 8989
	}
	if strings.TrimSpace(model) == "" {
		model = DefaultModel
	}
	cfg := fmt.Sprintf(configTmpl, model, port)
	return atomicWrite(filepath.Join(home, "config.toml"), []byte(cfg))
}

func atomicWrite(path string, b []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, b, 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// values are generated (key alnum, model/port panel-validated) so %q/%d suffice
const configTmpl = `# generated by usb-bridge -- edits are overwritten on unlock / panel change
model = %q
model_provider = "bridge"
disable_response_storage = true

[model_providers.bridge]
name = "USB Bridge"
base_url = "http://127.0.0.1:%d/v1"
wire_api = "responses"
env_key = "OPENAI_API_KEY"
`
